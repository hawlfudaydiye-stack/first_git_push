# 1. Waydiiso isticmaalaha qoraalka
geli = input("Geli qoraalka si luguugu tiriyo: ")

# 2. Isticmaal .split() si aad qoraalka ugu qaybiso liis kelmado ah
kelmadaha_liis = geli.split()

# 3. Isticmaal len() si aad u ogaato inta ay yihiin kelmadahaas
tirada = len(kelmadaha_liis)

# 4. Daabac natiijada
print(f"Kelmadaha total waa: {tirada}")

